  expect(property('color').computed).toBe('rgb(255, 0, 0)');
  expect(property('color').declarations[0].important).toBe(true);
  expect(property('margin-top').declarations[0].layer).toBe('second');
  expect(property('padding-top').declarations[0].layer).toBe('first');
  expect(property('opacity').declarations[0].inline).toBe(true);
  expect(property('border-top-width').declarations[0].value).toBe('2px');
