  await api('click', '[data-testid="logout"]');
  await expect.poll(async () => (await api('getState')).focused).toBe('login');
  await expect(route('Shop').getByTestId('user')).toHaveText('Guest');
  await api('navigate', '/checkout');
  await api('click', 'main button');
  await expect.poll(async () => (await api('getState')).focused).toBe('thanks');
  await expect.poll(async () => (await api('inspect', 'checkout')).route).toBe('/checkout');
  await expect(route('Home').getByTestId('cart')).toHaveText('0');
  await api('navigate', '/redirect');
  await expect.poll(async () => (await api('getState')).focused).toBe('shop');
  await expect(page.locator('.sw-blocked')).toContainText('redirects');
  expect((await api('inspect', 'redirect')).available).toBe(false);
  await api('show', 'redirect', false);
  // Concurrent agent navigation is serialized; the last requested destination wins.
  await page.evaluate(() => Promise.all([window.sitewall.navigate('/'), window.sitewall.navigate('/shop')]));
  expect((await api('getState')).focused).toBe('shop');
  await api('configure', { viewport: { width: 820, height: 900 }, zoom: .3, pan: { x: 10, y: 10 }, columns: 3 });
  expect((await api('inspect', 'home')).viewport).toEqual({ width: 820, height: 900 });
  expect(await page.locator('iframe[title="Home"]').evaluate(frame => ({
    iframe: frame.offsetWidth,
    body: frame.parentElement.clientWidth,
    panel: frame.closest('.sw-page').clientWidth,
  }))).toEqual({ iframe: 820, body: 820, panel: 820 });
  await api('navigate', '/story');
  await api('scroll', 0, 500);
  const images = await api('capture', 'story');
  expect(images.length).toBeGreaterThan(2);
  expect((await api('inspect', 'story')).viewport.height).toBe(900);
  expect((await api('inspect', 'story')).scroll.y).toBe(500);
  await api('show', 'story', false);
  await api('show', 'story', true);
  expect((await api('inspect', 'story')).scroll.y).toBe(500);
  // Applying source CSS inline must retain the original external sheet's URL base.
  await page.route('**/fixtures/styles/app.css', request => request.fulfill({ contentType: 'text/css', body: original }));
  await page.route('**/fixtures/assets/pixel.svg', request => request.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="1" height="1"><path fill="red" d="M0 0h1v1H0z"/></svg>' }));
  await route('Home').locator('body').evaluate(async body => {
    const link = document.querySelector('link[href="/app.css"]');
    await new Promise((resolve, reject) => { link.onload = resolve; link.onerror = reject; link.href = '/fixtures/styles/app.css'; });
    const probe = document.createElement('div'); probe.className = 'relative-probe'; body.append(probe);
  });
  await api('focus', 'home');
  await api('clearSelection');
  await expect(page.locator('.sw-style-rule[data-rule-index="11"]')).toBeVisible();
  await expect(page.locator('.sw-style-rule[data-rule-index="8"]')).toHaveCount(0);
  await api('selectElement', 'h1', 'home');
  const ruleCard = page.locator('.sw-style-rule[data-rule-index="2"]');
  const editor = ruleCard.getByLabel('CSS rule content');
  const editorText = () => editor.evaluate(el => [...el.querySelectorAll('.cm-line')].map(line => line.textContent).join('\n'));
  await expect(editor).toBeVisible();
  await expect.poll(editorText).toContain('font-size: 37px');
  await expect(page.locator('.cm-lineNumbers')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Format CSS', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Reopen from disk', exact: true })).toHaveCount(0);
  await expect(page.locator('.sw-styles')).not.toContainText('APPLICATION STYLES');
  await expect(page.locator('.sw-style-rule[data-rule-index="8"]')).toHaveCount(0);
  await expect(page.locator('.sw-style-rule[data-rule-index="11"]')).toHaveCount(0);
  await expect(ruleCard.locator('.sw-rule-filename')).toHaveText('examples/app.css');
  await page.getByLabel('Filter styles').fill('does-not-match');
  await expect(editor).toBeHidden();
  await api('filterStyles', 'font-size');
  await expect(page.getByLabel('Filter styles')).toHaveValue('font-size');
