import { expect } from '@playwright/test';
export async function verifyFeatures(page, api, route) {
  await page.getByLabel('Auto Centering').uncheck();
  expect((await api('getState')).autoCenter).toBe(false);
  const panBeforeFocus = (await api('getState')).pan;
  await api('focus', 'shop');
  await page.waitForTimeout(50);
  expect((await api('getState')).pan).toEqual(panBeforeFocus);
  await api('focus', 'home');
  await api('configure', { zoom: .65, pan: { x: 24, y: 24 } });
  const zoomProof = await page.evaluate(async () => {
    const canvas = document.querySelector('.sw-canvas');
    const bounds = canvas.getBoundingClientRect();
    const origin = { x: 130 + canvas.scrollLeft, y: 150 + canvas.scrollTop };
    const layoutOrigin = { x: canvas.querySelector('.sw-wall').offsetLeft, y: canvas.querySelector('.sw-wall').offsetTop };
    const before = window.sitewall.getState();
    const world = { x: (origin.x - layoutOrigin.x - before.pan.x) / before.zoom, y: (origin.y - layoutOrigin.y - before.pan.y) / before.zoom };
    canvas.dispatchEvent(new WheelEvent('wheel', { bubbles: true, cancelable: true, ctrlKey: true, deltaY: -70, clientX: bounds.left + 130, clientY: bounds.top + 150 }));
    const samples = [];
    for (let i = 0; i < 35; i++) { await new Promise(requestAnimationFrame); const state = window.sitewall.getState(); samples.push({ zoom: state.zoom, dx: layoutOrigin.x + state.pan.x + world.x * state.zoom - origin.x, dy: layoutOrigin.y + state.pan.y + world.y * state.zoom - origin.y }); }
    return { before: before.zoom, samples };
  });
  expect(zoomProof.samples.at(-1).zoom).toBeGreaterThan(zoomProof.before);
  expect(new Set(zoomProof.samples.map(sample => sample.zoom)).size).toBeGreaterThan(5);
  expect(zoomProof.samples.every(sample => Math.abs(sample.dx) < .001 && Math.abs(sample.dy) < .001)).toBe(true);
  await api('configure', { zoom: .65, pan: { x: 24, y: 24 } });
  // Explicitly map the page's viewport rectangle through the iframe's CSS scale.
  const headingBounds = () => page.locator('iframe[title="Home"]').evaluate(frame => {
    const outer = frame.getBoundingClientRect();
    const inner = frame.contentDocument.querySelector('h1').getBoundingClientRect();
    const scale = outer.width / frame.offsetWidth;
    return { x: outer.x + inner.x * scale, y: outer.y + inner.y * scale };
  });
  const iframeAnchor = await headingBounds();
  const pointer = { x: iframeAnchor.x + 30, y: iframeAnchor.y + 20 };
  await page.mouse.move(pointer.x, pointer.y);
  await page.keyboard.down('Control');
  await page.mouse.wheel(0, -60);
  await page.keyboard.up('Control');
  await expect.poll(async () => (await api('getState')).zoom).toBeGreaterThan(.65);
  await page.waitForTimeout(600);
  const zoomedHeading = await headingBounds();
  const scale = (await api('getState')).zoom / .65;
  expect(zoomedHeading.x + 30 * scale).toBeCloseTo(pointer.x, 0);
  expect(zoomedHeading.y + 20 * scale).toBeCloseTo(pointer.y, 0);
  await api('configure', { zoom: .65, pan: { x: 24, y: 24 } });
  await page.getByRole('button', { name: 'Select element', exact: true }).click();
  const browse = await route('Home').getByTestId('browse').boundingBox();
  await page.mouse.click(browse.x + 10, browse.y + 5);
  expect((await api('getState')).focused).toBe('home');
  expect((await api('inspectSelection')).element.tag).toBe('a');
  await page.getByRole('button', { name: 'Select element', exact: true }).click();
  const heading = await route('Home').locator('h1').boundingBox();
  await page.mouse.click(heading.x + 20, heading.y + 20);
  const selection = await api('inspectSelection');
  expect(selection.kind).toBe('element');
  expect(selection.element.tag).toBe('h1');
  expect(selection.route).toBe('/');
  expect(selection.rectangle.width).toBeGreaterThan(0);
  await expect(page.locator('.sw-selection-box')).toBeVisible();
  const context = await api('promptContext');
  expect(context.selection.element.selector).toBe(selection.element.selector);
  expect(context.applicationState.cart).toBe(0);
  expect(context.history.some(event => event.type === 'click')).toBe(true);
  expect(context.styles.cascade.some(property => property.property === 'color')).toBe(true);
  await page.getByRole('button', { name: 'Select region', exact: true }).click();
  const overlay = await page.getByLabel('Select context in home', { exact: true }).boundingBox();
  await page.mouse.move(overlay.x + 20, overlay.y + 30);
  await page.mouse.down();
  await page.mouse.move(overlay.x + 150, overlay.y + 180, { steps: 6 });
  await page.mouse.up();
  const region = await api('inspectSelection');
  expect(region.kind).toBe('region');
  expect(region.rectangle.width).toBeCloseTo(200, 0);
  expect(region.rectangle.height).toBeCloseTo(150 / .65, 0);
  expect(region.surroundingElements.length).toBeGreaterThan(0);
  expect((await api('promptContext')).styles.region.length).toBeGreaterThan(0);
  await page.getByRole('button', { name: 'Prompt Agent', exact: true }).click();
  await page.getByLabel('Instruction for Agent').fill('Make this section visually quieter.');
  await page.getByLabel('Instruction for Agent').press('Enter');
  await expect(page.getByLabel('Agent output history')).toContainText('Simulated Codex execution');
  const relayState = await page.evaluate(async () => {
    const response = await fetch('/__sitewall/session', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-SiteWall-Token': window.demoToken }, body: JSON.stringify({ method: 'getState', args: [] }) });
    if (!response.ok) throw new Error(await response.text());
    return (await response.json()).result;
  });
  expect(relayState.selection.rectangle).toEqual(region.rectangle);
  expect(relayState.focused).toBe('home');
  await page.screenshot({ path: new URL('../.artifacts/selection-prompt.png', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
  await api('clearSelection');
  expect(await api('inspectSelection')).toBeNull();
  await expect(page.locator('.sw-selection-box')).toHaveCount(0);
}
